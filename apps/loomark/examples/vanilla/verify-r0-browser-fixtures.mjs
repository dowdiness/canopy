import assert from "node:assert/strict"
import { execFile } from "node:child_process"
import { mkdtemp, readFile, readdir, rm } from "node:fs/promises"
import { tmpdir } from "node:os"
import { basename, join } from "node:path"
import { fileURLToPath } from "node:url"
import { promisify } from "node:util"
import { sha256 } from "./r0-browser-fixtures.mjs"

const execFileAsync = promisify(execFile)
const fixtureRoot = fileURLToPath(new URL("./fixtures/r0-browser-v1/", import.meta.url))
const generatorPath = fileURLToPath(new URL("./generate-r0-browser-fixtures.mjs", import.meta.url))
const regeneratedRoot = await mkdtemp(join(tmpdir(), "loomark-r0-browser-regenerated-"))

try {
  await execFileAsync(process.execPath, [generatorPath], {
    env: {
      ...process.env,
      LOOMARK_R0_BROWSER_FIXTURE_OUTPUT: regeneratedRoot,
      NEW_MOON_MOD: "0",
    },
    maxBuffer: 32 * 1024 * 1024,
  })
  const checkedInNames = (await readdir(fixtureRoot)).sort()
  const regeneratedNames = (await readdir(regeneratedRoot)).sort()
  assert.deepEqual(regeneratedNames, checkedInNames, "regenerated fixture filenames differ")
  const hashes = []
  for (const name of checkedInNames) {
    const checkedIn = await readFile(join(fixtureRoot, name))
    const regenerated = await readFile(join(regeneratedRoot, name))
    assert.deepEqual(regenerated, checkedIn, `${name}: regenerated bytes differ`)
    hashes.push({ path: basename(name), sha256: sha256(checkedIn), bytes: checkedIn.length })
  }
  process.stdout.write(`${JSON.stringify({ verdict: "pass", hashes }, null, 2)}\n`)
} finally {
  await rm(regeneratedRoot, { recursive: true, force: true })
}
